"""
Markdown report generators for the export endpoints (news search, country dossier).
Pure functions over the same dicts the API returns — PDF is the browser's print-to-PDF of the
rendered page (frontend "PRINT / PDF" button), so nothing heavy is needed server-side.
"""
from datetime import datetime


def _h(ts) -> str:
    if isinstance(ts, datetime):
        return ts.strftime("%Y-%m-%d %H:%M UTC")
    return str(ts or "")


def news_markdown(data: dict) -> str:
    stories = data.get("results") or []
    md = [f"# SENTINEL intelligence report — “{data.get('query', '')}”",
          f"*{data.get('total_articles', 0)} articles · {len(stories)} stories · "
          f"{len(data.get('contradictions') or [])} contradictions · generated {_h(data.get('timestamp') or datetime.utcnow())}*", ""]
    if data.get("contradictions"):
        md.append("## ⚡ Contradictions")
        for c in data["contradictions"]:
            md.append(f"- **{c.get('conflict', 'conflicting claims')}** ({c.get('method', 'keyword')} judge): "
                      f"“{c.get('story1')}” vs “{c.get('story2')}”")
        md.append("")
    md.append("## Stories")
    for i, s in enumerate(stories):
        t = s.get("trust") or {}
        md += [f"### {i + 1}. {(s.get('titles') or ['?'])[0]}",
               f"- Confidence: **{(s.get('confidence') or '').upper()}** ({s.get('source_count', len(s.get('sources') or []))} sources) · "
               f"Verdict: **{s.get('verdict', '')}** · Trust score: {s.get('trust_score', 0)}",
               f"- Trusted: {', '.join(t.get('trusted') or []) or '—'} · Unknown: {', '.join(t.get('unknown') or []) or '—'} · "
               f"Unreliable: {', '.join(t.get('unreliable') or []) or '—'}"]
        if s.get("geo"):
            md.append(f"- Location: {s['geo'].get('country')}")
        if s.get("claims"):
            md.append("- Claims:")
            for c in s["claims"]:
                tag = {"corroborated": "✅ corroborated", "disputed": "⚡ disputed"}.get(c.get("status"), "◌ single-source")
                md.append(f"  - {c.get('text')} — {tag}"
                          + (f" (supported by {', '.join('#' + str(x + 1) for x in c.get('supported_by') or [])})" if c.get("supported_by") else "")
                          + (f" (contradicted by {', '.join('#' + str(x + 1) for x in c.get('contradicted_by') or [])})" if c.get("contradicted_by") else ""))
        if s.get("entities"):
            md.append("- Entities: " + ", ".join(f"{e.get('name')} ({e.get('type')})" for e in s["entities"]))
        for a in s.get("articles") or []:
            md.append(f"- [{a.get('title')}]({a.get('url')}) — {a.get('source')}")
        md.append("")
    md += ["---", "Verdict rule: VERIFIED needs ≥1 trusted outlet, trust score ≥2 and ≥2 independent sources; "
           "any unreliable-list source → DISPUTED; single source → UNVERIFIED; otherwise NEEDS REVIEW.",
           "Generated by SENTINEL AI from public sources. Not affiliated with any government or agency."]
    return "\n".join(md)


def country_markdown(p: dict) -> str:
    md = [f"# {p.get('country', '')} — military dossier", "", p.get("military_summary", ""), "",
          "| Field | Value |", "|---|---|"]
    for label, key in [("Army", "army_strength"), ("Navy", "navy_strength"), ("Air force", "airforce_strength"),
                       ("Defence budget", "defense_budget"), ("Budget % GDP", "defense_budget_gdp_pct"),
                       ("Active personnel", "active_personnel"), ("Rank (by expenditure)", "global_rank")]:
        if p.get(key) not in (None, "", "N/A"):
            md.append(f"| {label} | {p[key]} |")
    md.append("")
    if p.get("key_weapons"):
        md += ["## Key weapons"] + [f"- {w}" for w in p["key_weapons"]] + [""]
    if p.get("notable_facts"):
        md += ["## Notable facts"] + [f"- {f}" for f in p["notable_facts"]] + [""]
    if p.get("expenditure_series"):
        md += ["## Military expenditure (World Bank, current US$)", "| Year | US$ |", "|---|---|"]
        md += [f"| {pt['year']} | {pt['value']:,.0f} |" for pt in p["expenditure_series"]] + [""]
    md += ["---", f"Sources: {p.get('data_source', '')}" + (f" · {p['source_url']}" if p.get("source_url") else ""),
           p.get("estimates_note", ""), "Generated by SENTINEL AI. OSINT only."]
    return "\n".join(md)
